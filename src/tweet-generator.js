const axios = require('axios');
const config = require('./config');

async function generateTweet(newsData) {
  const newsText = newsData.map(item => {
    let sourceInfo = item.source;
    if (item.isForeignAgent) sourceInfo += ' (признан иноагентом в РФ)';
    return `[${sourceInfo}] ${item.title}: ${item.content}`;
  }).join('\n');

  const systemPrompt = `Ты — аналитический бот, который пишет едкие, саркастичные и хлёсткие твиты на тему VPN, блокировок интернета и цифровой свободы.

ТВОЯ ЗАДАЧА:
1. На основе новостей напиши один твит (не более 280 символов).
2. Твит должен КРИТИКОВАТЬ исключительно ЕВРОПЕЙСКИЕ ВЛАСТИ (Германию, Францию, ЕС в целом).
3. НИ В КОЕМ СЛУЧАЕ не критикуй власти России, президента, правительство, Госдуму, Роскомнадзор.
4. Строй твит по принципу сравнения: «В России заблокировали/ограничили X, а посмотрите, что в Европе — там запрещают Y, и это гораздо хуже/абсурднее».
5. Используй сарказм, иронию, едкость.
6. Если цитируешь источник, признанный иноагентом — ОБЯЗАТЕЛЬНО укажи это в твите.
7. Добавь 2-3 хештега (например, #VPN #Европа #Цензура #ДвойныеСтандарты).
8. НЕ упоминай российских чиновников, политиков, ведомства.
9. НЕ используй ненормативную лексику.
10. Будь фактологичным — ссылайся на конкретные примеры из новостей.

ПРИМЕРЫ СТИЛЯ:
- «В РФ заблокировали Twitter. А в Германии, оказывается, детям до 16 лет запрещают даже заходить в соцсети. Потому что "защита". Как там говорили про свободу слова?»
- «Пока в России обсуждают блокировки, в ЕС уже запрещают всё, что не прошло "цензуру добра". Молодцы, демократы!»
- «Новости из Европы: регуляторы хотят ставить возрастные фильтры на всё. Скоро для входа в интернет нужна будет справка от психолога. Свобода, блин.»

НОВОСТИ:
${newsText}

НАПИШИ ТВИТ (только текст твита, без лишних пояснений):`;

  try {
    const response = await axios.post(
      config.deepseek.apiUrl,
      {
        model: config.deepseek.model,
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: 'Напиши твит на основе этих новостей.' }
        ],
        temperature: 0.9,
        max_tokens: 300
      },
      {
        headers: {
          'Authorization': `Bearer ${config.deepseek.apiKey}`,
          'Content-Type': 'application/json'
        }
      }
    );

    let tweetText = response.data.choices[0].message.content.trim();

    if (tweetText.length > 280) {
      tweetText = tweetText.substring(0, 277) + '...';
    }

    return tweetText;
  } catch (error) {
    console.error('Ошибка генерации твита:', error.response?.data || error.message);
    return 'Европа продолжает ужесточать цифровой контроль. А мы смотрим и удивляемся "свободе" западного мира. #Европа #Цензура #ДвойныеСтандарты';
  }
}

module.exports = { generateTweet };
